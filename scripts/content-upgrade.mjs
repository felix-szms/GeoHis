// ---------- 工具：在折线上按坐标匹配替换点 ----------
function replacePt(route, pt, replacement) {
  const i = route.findIndex((p) => p[0] === pt[0] && p[1] === pt[1]);
  if (i >= 0) route.splice(i, 1, ...replacement);
  else console.log(`  ! 未找到折线点 ${pt}`);
}

